function replaceOnce(source, oldText, newText) {
  if (source.split(oldText).length !== 2) throw new Error('Upstream changed: adaptation no longer matches exactly once');
  return source.replace(oldText, newText);
}
function silentHelper(source, name) {
  const begin = source.indexOf(`\n  function ${name}(`);
  const end = source.indexOf('\n  function ', begin + 3);
  if (begin < 0 || end < 0) throw new Error(`Missing upstream helper ${name}`);
  return source.slice(0, begin) + `\n  function ${name}() {}\n` + source.slice(end);
}
